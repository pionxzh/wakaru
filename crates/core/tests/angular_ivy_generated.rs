use std::collections::HashMap;

use wakaru_core::{
    recover_angular_components_from_js, recover_angular_components_from_modules,
    AngularModuleSource, AngularRecoveryCompleteness, AngularRecoveryOptions,
};

const RUNTIME: &str = include_str!("bundles/angular-ivy-gen/dist/runtime.js");
const MAIN: &str = include_str!("bundles/angular-ivy-gen/dist/main.js");
const LAZY: &str = include_str!("bundles/angular-ivy-gen/dist/lazy.js");
const CLOSURE_SIMPLE: &str = include_str!("bundles/angular-ivy-gen/dist/closure-simple.js");

fn assert_production_artifact(source: &str) {
    assert!(!source.contains("ɵsetClassMetadata"));
    assert!(!source.contains("template: `"));
    assert!(!source.contains("<article"));
}

#[test]
fn recovers_components_from_angular_cli_production_chunks() {
    assert_production_artifact(RUNTIME);
    assert_production_artifact(MAIN);
    assert_production_artifact(LAZY);

    let recovered = recover_angular_components_from_modules(
        &[
            AngularModuleSource {
                filename: "runtime.js",
                source: RUNTIME,
            },
            AngularModuleSource {
                filename: "main.js",
                source: MAIN,
            },
            AngularModuleSource {
                filename: "lazy.js",
                source: LAZY,
            },
        ],
        AngularRecoveryOptions::default(),
    )
    .expect("pinned Angular production chunks should parse");

    let by_selector = recovered
        .iter()
        .map(|component| (component.selector.as_str(), component))
        .collect::<HashMap<_, _>>();
    assert_eq!(by_selector.len(), 3);
    assert_eq!(
        by_selector["fixture-card"].completeness,
        AngularRecoveryCompleteness::Complete
    );
    assert!(by_selector["fixture-card"].source.contains(
        "<button type=\"button\" (click)=\"select()\" [disabled]=\"disabled\">Select</button>"
    ));
    assert!(by_selector["fixture-card"]
        .source
        .contains("title = \"Generated by Angular\""));
    assert!(by_selector["app-root"]
        .source
        .contains("<fixture-card></fixture-card>"));
    assert!(by_selector.contains_key("fixture-lazy-card"));
}

#[test]
fn recovers_the_same_components_after_closure_simple() {
    assert_production_artifact(CLOSURE_SIMPLE);

    let recovered =
        recover_angular_components_from_js(CLOSURE_SIMPLE, AngularRecoveryOptions::default())
            .expect("pinned Closure output should parse");
    let selectors = recovered
        .iter()
        .map(|component| component.selector.as_str())
        .collect::<std::collections::HashSet<_>>();

    assert_eq!(selectors.len(), 3);
    assert!(selectors.contains("app-root"));
    assert!(selectors.contains("fixture-card"));
    assert!(selectors.contains("fixture-lazy-card"));
}
